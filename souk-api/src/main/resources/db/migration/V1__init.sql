-- Utilisateurs (vendeurs et acheteurs)
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    governorate   VARCHAR(30),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Fiche commune à toutes les annonces
CREATE TABLE listings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        BIGINT        NOT NULL REFERENCES users (id),
    category         VARCHAR(20)   NOT NULL,
    transaction_type VARCHAR(20)   NOT NULL,
    title            VARCHAR(120)  NOT NULL,
    description      TEXT,
    price            NUMERIC(12,3) NOT NULL CHECK (price >= 0),
    governorate      VARCHAR(30)   NOT NULL,
    city             VARCHAR(80)   NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Annexe : véhicules
CREATE TABLE vehicle_listings (
    listing_id BIGINT      PRIMARY KEY REFERENCES listings (id) ON DELETE CASCADE,
    brand      VARCHAR(50) NOT NULL,
    model      VARCHAR(50) NOT NULL,
    model_year INTEGER     NOT NULL,
    mileage_km INTEGER     NOT NULL CHECK (mileage_km >= 0),
    fuel       VARCHAR(20) NOT NULL,
    gearbox    VARCHAR(20) NOT NULL
);

-- Annexe : immobilier
CREATE TABLE property_listings (
    listing_id    BIGINT      PRIMARY KEY REFERENCES listings (id) ON DELETE CASCADE,
    property_type VARCHAR(20) NOT NULL,
    surface_m2    INTEGER     NOT NULL CHECK (surface_m2 > 0),
    rooms         INTEGER,
    furnished     BOOLEAN     NOT NULL DEFAULT FALSE
);

-- Index pour la recherche et pour "mes annonces"
CREATE INDEX idx_listings_search ON listings (category, status, governorate);
CREATE INDEX idx_listings_seller ON listings (seller_id);
